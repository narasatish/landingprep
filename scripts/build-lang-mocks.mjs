// Bakes the verified German/French A1 item pools (data/*-pool.json, gitignored) into
// the committed, browser-loaded lang-mock-data.jsx. A small in-file generator assembles
// 30 distinct mock tests per language by rotating through the pools. Re-run after editing
// the pools:  node scripts/build-lang-mocks.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const de = JSON.parse(fs.readFileSync(path.join(ROOT, "data/de-pool.json"), "utf8"));
const fr = JSON.parse(fs.readFileSync(path.join(ROOT, "data/fr-pool.json"), "utf8"));
const es = JSON.parse(fs.readFileSync(path.join(ROOT, "data/es-pool.json"), "utf8"));

// Strict validation — fail loudly rather than ship bad answers.
function validate(pool, name) {
  const rq = pool.reading.flatMap((r) => r.questions);
  const all = [...pool.grammar, ...pool.listening, ...rq];
  const bad = all.filter((x) => !Array.isArray(x.options) || x.options.length !== 4 || !(x.answer >= 0 && x.answer <= 3));
  if (bad.length) throw new Error(`${name}: ${bad.length} items with out-of-range answer / wrong option count`);
  if (pool.reading.length < 6 || pool.grammar.length < 24 || pool.listening.length < 20)
    throw new Error(`${name}: pool too small (${pool.reading.length}/${pool.grammar.length}/${pool.listening.length})`);
  if (pool.reading.some((r) => !r.passage || r.questions.length !== 4)) throw new Error(`${name}: bad reading passage`);
}
validate(de, "german");
validate(fr, "french");
validate(es, "spanish");

const CFG = {
  de: { name: "German", style: "Goethe-style",
    readingTitle: "Lesen · Reading", grammarTitle: "Grammatik & Wortschatz · Grammar & Vocabulary", listeningTitle: "Hören · Listening" },
  fr: { name: "French", style: "DELF-style",
    readingTitle: "Compréhension écrite · Reading", grammarTitle: "Grammaire & Vocabulaire · Grammar & Vocabulary", listeningTitle: "Compréhension orale · Listening" },
  es: { name: "Spanish", style: "DELE-style",
    readingTitle: "Comprensión de lectura · Reading", grammarTitle: "Gramática y Vocabulario · Grammar & Vocabulary", listeningTitle: "Comprensión auditiva · Listening" },
};

const file = `/* global window */
"use strict";
// LandingPrep — German/French language MOCK TESTS (Goethe-A1 / DELF-A1 style).
// AUTO-GENERATED by scripts/build-lang-mocks.mjs from verified item pools — DO NOT edit by
// hand; edit data/de-pool.json / data/fr-pool.json and re-run the script.
// 30 mock tests per language, each: Reading (Lesen/Compréhension écrite) + Grammar &
// Vocabulary + Listening (Hören/Compréhension orale, spoken via the live native voice).
// Schema per mock: { id, level, title, minutes, sections:[{ type, title, intro?, passage?,
//   questions:[{ q, options:[...], answer:<index>, audio? }] }] }
(function () {
  var DE_POOL = ${JSON.stringify(de)};
  var FR_POOL = ${JSON.stringify(fr)};
  var ES_POOL = ${JSON.stringify(es)};
  var CFG = ${JSON.stringify(CFG)};
  var COUNT = 30;

  function pick(arr, start, n) {
    var out = [];
    for (var k = 0; k < n; k++) out.push(arr[(start + k) % arr.length]);
    return out;
  }
  function buildMocks(pool, code) {
    var c = CFG[code];
    var mocks = [];
    for (var i = 0; i < COUNT; i++) {
      var r = pool.reading[i % pool.reading.length];
      mocks.push({
        id: code + "-a1-mock-" + (i + 1), level: "A1",
        title: c.name + " A1 Mock Test " + (i + 1) + " (" + c.style + ")", minutes: 30,
        sections: [
          { type: "reading", title: c.readingTitle, intro: "Read the text, then answer the questions.", passage: r.passage, questions: r.questions },
          { type: "grammar", title: c.grammarTitle, intro: "Choose the correct option.", questions: pick(pool.grammar, (i * 8) % pool.grammar.length, 8) },
          { type: "listening", title: c.listeningTitle, intro: "Tap \\u25B6 to hear each sentence, then answer.", questions: pick(pool.listening, (i * 5) % pool.listening.length, 5) },
        ],
      });
    }
    return mocks;
  }

  window.LP_LANG_MOCKS = { german: buildMocks(DE_POOL, "de"), french: buildMocks(FR_POOL, "fr"), spanish: buildMocks(ES_POOL, "es") };
})();
`;

fs.writeFileSync(path.join(ROOT, "lang-mock-data.jsx"), file);
console.log("Wrote lang-mock-data.jsx —", file.split("\n").length, "lines,", file.length, "bytes");
