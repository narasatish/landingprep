// Assembles exam-extra.js from the per-exam *-extra.json banks. This file is loaded
// by MockTestGate right after data-questions.js and APPENDS the extra questions into
// window.LP_QUESTIONS so the mock builder has enough distinct items (no cycle-repeats).
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const read = (f) => { try { return JSON.parse(fs.readFileSync(path.join(ROOT, "data", f), "utf8")); } catch { return null; } };

const toefl = read("toefl-extra.json");
const gre = read("gre-extra.json");
const gmat = read("gmat-extra.json");
const pte = read("pte-extra.json");

const out = `/* AUTO-GENERATED by scripts/build-exam-extra.mjs — do not edit by hand.
   Appends extra question banks so every mock has enough distinct items (no repeats). */
(function () {
  var Q = window.LP_QUESTIONS;
  if (!Q || Q.__extra) return;
  Q.__extra = true;
  function push(arr, items) { if (Array.isArray(arr) && Array.isArray(items)) arr.push.apply(arr, items); }
  try {
    var T = ${JSON.stringify(toefl || {})};
    if (Q.toefl) { push(Q.toefl.reading && Q.toefl.reading.passages, T.readingPassages); push(Q.toefl.listening && Q.toefl.listening.excerpts, T.listeningExcerpts); }
    var G = ${JSON.stringify(gre || {})};
    if (Q.gre) { push(Q.gre.verbal, G.verbal); push(Q.gre.quantitative, G.quantitative); }
    var M = ${JSON.stringify(gmat || {})};
    if (Q.gmat) { push(Q.gmat.quantitative, M.quantitative); push(Q.gmat.verbal, M.verbal); push(Q.gmat.dataInsights, M.dataInsights); }
    var P = ${JSON.stringify(pte || {})};
    if (Q.pte) { push(Q.pte.reading, P.reading); push(Q.pte.listening, P.listening); }
  } catch (e) { /* never block the test runner */ }
})();
`;

fs.writeFileSync(path.join(ROOT, "exam-extra.js"), out);
const n = (x, ...k) => (x ? k.reduce((a, key) => a + ((x[key] || []).length), 0) : 0);
console.log("✓ exam-extra.js written |",
  "TOEFL:", n(toefl, "readingPassages", "listeningExcerpts"),
  "GRE:", n(gre, "verbal", "quantitative"),
  "GMAT:", n(gmat, "quantitative", "verbal", "dataInsights"),
  "PTE:", n(pte, "reading", "listening"));
